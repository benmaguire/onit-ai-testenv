// Package telegraf generates a Telegraf configuration that polls every device
// over its real protocols (Modbus TCP, SNMP, Redfish) like a DCIM/BMS would,
// and exports what it reads for Prometheus. It is the end-to-end check that
// the protocol endpoints work, and a starting point for real collectors.
package telegraf

import (
	"fmt"
	"strconv"
	"strings"

	"github.com/benmaguire/onit-ai-testenv/environments/dc-ot-sim/otsim/internal/profile"
	"github.com/benmaguire/onit-ai-testenv/environments/dc-ot-sim/otsim/internal/site"
)

// Options controls how devices are addressed.
type Options struct {
	// HostTemplate builds a device's host name; "{id}" is replaced (e.g. "otsim-{id}").
	HostTemplate string
	ModbusPort   int
	SNMPPort     int
	Community    string
	// RedfishURL is the Redfish service base (e.g. http://otsim:8443).
	RedfishURL string
	Interval   string
	Listen     string
}

func dataType(t string) (string, string) {
	switch t {
	case "int16":
		return "INT16", "AB"
	case "uint32":
		return "UINT32", "ABCD"
	case "int32":
		return "INT32", "ABCD"
	case "float32":
		return "FLOAT32-IEEE", "ABCD"
	}
	return "UINT16", "AB"
}

// tomlFloat formats f as a TOML float: Telegraf rejects integer literals
// (e.g. "1") for float fields such as the modbus scale.
func tomlFloat(f float64) string {
	s := strconv.FormatFloat(f, 'g', -1, 64)
	if !strings.ContainsAny(s, ".eEn") { // n: NaN/Inf never occur here
		s += ".0"
	}
	return s
}

func registers(key string, es []profile.ModbusEntry) string {
	var rows []string
	for _, e := range es {
		if e.Point == "" || e.Type == "string" {
			continue // constants and identity strings
		}
		dt, bo := dataType(e.Type)
		addr := fmt.Sprintf("[%d]", e.Addr)
		if bo == "ABCD" {
			addr = fmt.Sprintf("[%d, %d]", e.Addr, e.Addr+1)
		}
		scale := 1.0
		if e.Scale != 0 {
			scale = 1 / e.Scale
		}
		rows = append(rows, fmt.Sprintf("    { name = %q, byte_order = %q, data_type = %q, scale = %s, address = %s },", e.Point, bo, dt, tomlFloat(scale), addr))
	}
	if len(rows) == 0 {
		return ""
	}
	return fmt.Sprintf("  %s = [\n%s\n  ]\n", key, strings.Join(rows, "\n"))
}

func bits(key string, es []profile.ModbusEntry) string {
	var rows []string
	for _, e := range es {
		rows = append(rows, fmt.Sprintf("    { name = %q, address = [%d] },", e.Point, e.Addr))
	}
	if len(rows) == 0 {
		return ""
	}
	return fmt.Sprintf("  %s = [\n%s\n  ]\n", key, strings.Join(rows, "\n"))
}

// Generate returns telegraf.conf.
func Generate(st *site.Site, set *profile.Set, o Options) string {
	if o.Interval == "" {
		o.Interval = "10s"
	}
	if o.Listen == "" {
		o.Listen = ":9273"
	}
	host := func(id string) string { return strings.ReplaceAll(o.HostTemplate, "{id}", id) }
	var b strings.Builder
	fmt.Fprintf(&b, "# Generated by `otsim telegraf-config` for site %q (region %s). Do not edit.\n", st.Config().Site.Name, st.Region().Name)
	fmt.Fprintf(&b, "# Values are as read on the wire: Modbus maps with regionUnits use the region's display units.\n\n")
	fmt.Fprintf(&b, "[agent]\n  interval = %q\n  omit_hostname = true\n\n[[outputs.prometheus_client]]\n  listen = %q\n  metric_version = 2\n\n", o.Interval, o.Listen)
	for _, d := range st.Devices() {
		if name, ok := d.Protocols["modbus"]; ok {
			m := set.Modbus[name]
			fmt.Fprintf(&b, "# %s (%s) over Modbus TCP, map %s\n[[inputs.modbus]]\n  name = \"otsim_modbus\"\n  slave_id = 1\n  timeout = \"3s\"\n  controller = \"tcp://%s:%d\"\n",
				d.ID, d.Type, name, host(d.ID), o.ModbusPort)
			b.WriteString(registers("holding_registers", m.Holding))
			b.WriteString(registers("input_registers", m.Input))
			b.WriteString(bits("coils", m.Coils))
			b.WriteString(bits("discrete_inputs", m.Discrete))
			fmt.Fprintf(&b, "  [inputs.modbus.tags]\n    device = %q\n    device_type = %q\n\n", d.ID, d.Type)
		}
		if name, ok := d.Protocols["snmp"]; ok {
			m := set.SNMP[name]
			fmt.Fprintf(&b, "# %s (%s) over SNMPv2c, profile %s\n[[inputs.snmp]]\n  name = \"otsim_snmp\"\n  agents = [\"udp://%s:%d\"]\n  version = 2\n  community = %q\n  timeout = \"3s\"\n",
				d.ID, d.Type, name, host(d.ID), o.SNMPPort, o.Community)
			fmt.Fprintf(&b, "  [inputs.snmp.tags]\n    device = %q\n    device_type = %q\n", d.ID, d.Type)
			for _, obj := range m.Objects {
				if obj.Point == "" {
					continue
				}
				fmt.Fprintf(&b, "  [[inputs.snmp.field]]\n    name = %q\n    oid = %q\n", obj.Point, obj.OID)
			}
			for i, s := range m.Sensors {
				fmt.Fprintf(&b, "  [[inputs.snmp.field]]\n    name = %q\n    oid = \"1.3.6.1.2.1.99.1.1.1.4.%d\"\n", s.Point, i+1)
			}
			b.WriteString("\n")
		}
		if _, ok := d.Protocols["redfish"]; ok && o.RedfishURL != "" {
			var url string
			var fields [][2]string
			switch d.Type {
			case "cdu":
				url = fmt.Sprintf("%s/redfish/v1/ThermalEquipment/CDUs/%s/SecondaryCoolantConnectors/1", o.RedfishURL, d.ID)
				fields = [][2]string{{"SupplyTemperatureCelsius.Reading", "supply_temp_c"}, {"ReturnTemperatureCelsius.Reading", "return_temp_c"},
					{"FlowLitersPerMinute.Reading", "flow_lpm"}, {"DeltaPressurekPa.Reading", "delta_pressure_kpa"}}
			case "rack-pdu":
				url = fmt.Sprintf("%s/redfish/v1/PowerEquipment/RackPDUs/%s/Metrics", o.RedfishURL, d.ID)
				fields = [][2]string{{"PowerWatts.Reading", "power_w"}, {"EnergykWh.Reading", "energy_kwh"}}
			default:
				continue
			}
			fmt.Fprintf(&b, "# %s (%s) over Redfish\n[[inputs.http]]\n  name_override = \"otsim_redfish\"\n  urls = [%q]\n  timeout = \"3s\"\n  data_format = \"json_v2\"\n", d.ID, d.Type, url)
			fmt.Fprintf(&b, "  [inputs.http.tags]\n    device = %q\n    device_type = %q\n  [[inputs.http.json_v2]]\n", d.ID, d.Type)
			for _, f := range fields {
				fmt.Fprintf(&b, "    [[inputs.http.json_v2.field]]\n      path = %q\n      rename = %q\n      type = \"float\"\n", f[0], f[1])
			}
			b.WriteString("\n")
		}
	}
	return b.String()
}
