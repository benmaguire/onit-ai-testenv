// Command gencatalog writes CATALOG.md from the simulation registry, so the
// documented catalog always matches what the controller serves.
//
//	go run ./hack/gencatalog > CATALOG.md
package main

import (
	"fmt"
	"os"
	"strings"

	"github.com/benmaguire/onit-ai-testenv/simulations/controller/internal/inject"
)

var categories = []struct{ key, title, intro string }{
	{"fault", "Generic faults (any workload)", "Network impairment (tc netem), outages (iptables, NetworkPolicy), resource stress and crashes, applied from an ephemeral container (`--tools-image`, default `nicolaka/netshoot:v0.16`) added to each target pod: it shares the pod's network namespace and cgroup, so only that pod is affected. Target pods with `target.namespace` + `target.podSelector` (or `graph`/`component` for Dynamo). Network impairment is egress: target a service's pods to slow its responses, its callers to slow their requests. One tc fault per pod at a time (enforced). Add `observe` to measure baseline / fault / recovery / after (see [docs/observability.md](docs/observability.md))."},
	{"gpu", "GPU (Mokka mock NVML)", "Injected with Mokka's `nvml-mock-ctl` in the `node-agent` container of the node's `nvml-mock` pod. Every mock-NVML consumer on the node (nvidia-smi, device plugin, GFD, dcgm-exporter, the Dynamo worker) sees the change within ~1s. Target a node (`target.node`, `target.nodeSelector`, default every Mokka node) and `target.gpu` (index, `all`, UUID; default `all`), **or** target pods (`target.graph`/`component`/`podSelector`) to hit exactly the GPUs those pods hold."},
	{"dynamo", "Dynamo", "Faults aimed at the Dynamo inference graph. With no target they default to the graph `mocker-agg` in namespace `nvidia-sim` (controller flags `--default-graph`, `--default-graph-namespace`); set `target.graph`/`target.namespace` for another graph."},
	{"kubernetes", "Kubernetes", "Generic faults for any workload."},
	{"network", "Network", "NetworkPolicy partitions, and link faults for emulated networks (the [network-kne environment](../../environments/network-kne/README.md)): take router interfaces down or flap them; combine with `net-*` faults on a router interface (`--param interface=eth1`) for degraded links."},
	{"observe", "Measurement only", "No fault: measure baseline / during / after around your own action. See [docs/observability.md](docs/observability.md)."},
	{"runai", "Run:ai (runai-sim)", "For the [runai-sim environment](../../environments/runai-sim/README.md): KWOK virtual GPU nodes (fake-gpu-operator) scheduled by KAI Scheduler. `pod-kill`, `network-isolate` and `node-cordon` work there too (target `--node-selector type=kwok` / the workload pods); GPU-through-Mokka and `dynamo-*` types do not apply to virtual nodes."},
}

func main() {
	cat := inject.NewRegistry(inject.All()...).Catalog()
	var b strings.Builder
	w := func(f string, a ...any) { fmt.Fprintf(&b, f, a...) }
	w("<!-- Generated by `go run ./hack/gencatalog > CATALOG.md` — do not edit by hand. -->\n\n")
	w("# Simulation catalog\n\n")
	w("Every simulation type the controller serves, for the nvidia-sim and runai-sim environments (also at `GET /api/v1/catalog` and `simctl catalog`). ")
	w("Each one injects a failure and has a defined recovery: what is reverted and what is checked before the Simulation reports `Recovered`.\n\n")
	w("| Type | Category | Summary |\n|---|---|---|\n")
	for _, e := range cat {
		w("| [`%s`](#%s) | %s | %s |\n", e.Type, e.Type, e.Category, e.Summary)
	}
	for _, c := range categories {
		w("\n## %s\n\n%s\n", c.title, c.intro)
		for _, e := range cat {
			if e.Category != c.key {
				continue
			}
			w("\n### %s\n\n%s.\n\n", e.Type, e.Summary)
			w("- **Effect:** %s\n- **Recovery:** %s\n- **Targets:** %s\n", e.Effect, e.Recovery, "`"+strings.Join(e.Targets, "`, `")+"`")
			for _, r := range e.Requires {
				w("- **Requires:** %s\n", r)
			}
			if len(e.Params) > 0 {
				w("\n| Param | Default | Description |\n|---|---|---|\n")
				for _, p := range e.Params {
					def := p.Default
					if p.Required {
						def = "**required**"
					} else if def == "" {
						def = "—"
					} else {
						def = "`" + def + "`"
					}
					w("| `%s` | %s | %s |\n", p.Name, def, p.Description)
				}
			}
			w("\n```bash\nsimctl inject %s%s --duration 2m --wait recovered\n```\n", e.Type, example(e.Type))
			if len(e.References) > 0 {
				w("\nReferences: ")
				for i, r := range e.References {
					if i > 0 {
						w(", ")
					}
					w("<%s>", r)
				}
				w("\n")
			}
		}
	}
	if _, err := os.Stdout.WriteString(b.String()); err != nil {
		os.Exit(1)
	}
}

func example(t string) string {
	switch t {
	case "gpu-xid":
		return " --graph mocker-agg --component decode --param xid=43 --param mode=lost"
	case "gpu-overheat":
		return " --node $NODE --gpu 0 --param temperature=98"
	case "gpu-memory-pressure":
		return " --gpu 0 --param usedPercent=97"
	case "gpu-set":
		return " --gpu 0 --param fields=pstate=8"
	case "pod-kill", "network-isolate", "cpu-stress", "memory-stress", "container-kill", "dns-outage":
		return " --target-namespace my-ns --pod-selector app=my-app"
	case "net-latency", "net-jitter", "net-packet-loss", "net-corruption", "net-duplication", "net-reorder", "net-bandwidth":
		return " --target-namespace my-ns --pod-selector app=my-app --observe kubernetes --baseline 2m --after 2m"
	case "net-degraded":
		return " --target-namespace my-ns --pod-selector app=my-app --param delay=80ms --param jitter=20ms --param loss=2 --param rate=10mbit"
	case "dependency-outage":
		return " --target-namespace my-ns --pod-selector app=api --param destinations=svc/postgres --param mode=drop"
	case "service-outage":
		return " --target-namespace my-ns --param service=my-svc --probe-http http://my-svc.my-ns:8080/healthz --baseline 1m --after 1m"
	case "link-down", "link-flap":
		return " --target-namespace kne-2node-xrd --pod-selector app=r1 --param interface=eth1"
	case "node-cordon":
		return " --node $NODE"
	case "observe-only":
		return " --target-namespace my-ns --observe kubernetes --baseline 5m --after 5m"
	case "kwok-node-down":
		return " --node-selector run.ai/simulated-gpu-node-pool=h100 --count 1"
	case "fgo-gpu-utilization":
		return " --target-namespace runai-sim --pod-selector app=train-whole-gpu --param range=0"
	}
	if strings.HasPrefix(t, "gpu-") && t != "gpu-device-plugin-restart" {
		return " --graph mocker-agg --component decode"
	}
	return ""
}
